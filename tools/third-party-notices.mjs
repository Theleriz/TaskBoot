#!/usr/bin/env node
// Generates THIRD_PARTY_NOTICES.md from the lock files (spec rule D-03).
//   node tools/third-party-notices.mjs          rewrite the file
//   node tools/third-party-notices.mjs --check  fail if the file is out of date (used in CI)
// Needs web/node_modules (npm ci) and the NuGet packages of win32/ restored (dotnet restore).
// The output is deterministic (sorted, no dates) so --check can compare it.

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'THIRD_PARTY_NOTICES.md');
const PERMISSIVE =
  /^(MIT|MIT-0|ISC|0BSD|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|CC0-1\.0|Unlicense|BlueOak-1\.0\.0|Python-2\.0|CC-BY-4\.0)$/;

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));
const normalize = (text) => text.replace(/\r\n/g, '\n').trim();

function licenseFile(dir) {
  if (!existsSync(dir)) return null;
  const name = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\..*)?$/i.test(f));
  return name ? normalize(readFileSync(join(dir, name), 'utf8')) : null;
}

function fence(text) {
  return '```text\n' + text + '\n```';
}

/* ---------- npm (web/) ---------- */

const lock = readJson(join(root, 'web', 'package-lock.json'));
const npmPackages = Object.entries(lock.packages)
  .filter(([path]) => path.startsWith('node_modules/'))
  .map(([path, info]) => ({
    path,
    name: path.split('node_modules/').pop(),
    version: info.version,
    license: info.license ?? 'UNKNOWN',
    dev: Boolean(info.dev),
  }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const shippedNpm = npmPackages.filter((p) => !p.dev);
const devNpm = npmPackages.filter((p) => p.dev);
const directDev = Object.keys(lock.packages[''].devDependencies ?? {}).sort();

function repoUrl(p) {
  const pkg = readJson(join(root, 'web', p.path, 'package.json'));
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  return (repo ?? pkg.homepage ?? '').replace(/^git\+/, '').replace(/\.git$/, '');
}

/* ---------- NuGet (win32/) ---------- */

const nugetRoot = process.env.NUGET_PACKAGES || join(homedir(), '.nuget', 'packages');
const nugetLock = readJson(join(root, 'win32', 'packages.lock.json'));
const nugetPackages = Object.entries(Object.values(nugetLock.dependencies)[0])
  .map(([name, info]) => ({ name, version: info.resolved, type: info.type }))
  .sort((a, b) => a.name.localeCompare(b.name));

function nugetLicense(pkg) {
  const dir = join(nugetRoot, pkg.name.toLowerCase(), pkg.version);
  const nuspecPath = join(dir, `${pkg.name.toLowerCase()}.nuspec`);
  if (!existsSync(nuspecPath)) {
    throw new Error(`NuGet package ${pkg.name} ${pkg.version} is not restored (${dir}). Run: dotnet restore win32/TaskTracker.csproj`);
  }
  const nuspec = readFileSync(nuspecPath, 'utf8');
  const expr = nuspec.match(/<license type="expression">([^<]+)<\/license>/);
  const file = nuspec.match(/<license type="file">([^<]+)<\/license>/);
  const notice = existsSync(join(dir, 'NOTICE.txt')) ? normalize(readFileSync(join(dir, 'NOTICE.txt'), 'utf8')) : null;
  return {
    expression: expr ? expr[1] : file ? 'see license text' : 'UNKNOWN',
    text: file ? normalize(readFileSync(join(dir, file[1]), 'utf8')) : licenseFile(dir),
    notice,
  };
}

// Packages whose files end up in the Windows app folder. Reference assemblies are compile-time only.
const SHIPPED_NUGET = new Set(['Microsoft.Web.WebView2']);

/* ---------- Output ---------- */

const out = [];
out.push('# Third-party notices');
out.push('');
out.push('Generated by `node tools/third-party-notices.mjs` from `web/package-lock.json` and `win32/packages.lock.json`. Do not edit by hand.');
out.push('');
out.push('Task Tracker includes the components listed under "Distributed" below. Their license texts follow each entry.');
out.push('');
out.push('## Distributed with the app');
out.push('');
out.push('### Web app (in the web build and inside the Windows app)');
out.push('');
for (const p of shippedNpm) {
  out.push(`#### ${p.name} ${p.version}`);
  out.push('');
  out.push(`License: ${p.license}. Source: ${repoUrl(p) || 'npm'}`);
  out.push('');
  const text = licenseFile(join(root, 'web', p.path));
  out.push(text ? fence(text) : '_License text not found in the package._');
  out.push('');
}

out.push('### Windows app');
out.push('');
for (const p of nugetPackages.filter((n) => SHIPPED_NUGET.has(n.name))) {
  const lic = nugetLicense(p);
  out.push(`#### ${p.name} ${p.version}`);
  out.push('');
  out.push(`License: ${lic.expression}. Source: https://www.nuget.org/packages/${p.name}`);
  out.push('');
  out.push(lic.text ? fence(lic.text) : '_License text not found in the package._');
  out.push('');
  if (lic.notice) {
    out.push(`Notices included with ${p.name}:`);
    out.push('');
    out.push(fence(lic.notice));
    out.push('');
  }
}
out.push('The Windows app also uses components of Windows itself (.NET Framework 4.8, Microsoft Edge WebView2 Runtime), which are not distributed with it.');
out.push('');

out.push('## Build and development only (not distributed)');
out.push('');
out.push('### npm: direct development dependencies');
out.push('');
out.push('| Package | Version | License |');
out.push('|---|---|---|');
for (const name of directDev) {
  const p = devNpm.find((x) => x.name === name && x.path === `node_modules/${name}`);
  if (p) out.push(`| ${p.name} | ${p.version} | ${p.license} |`);
}
out.push('');

const counts = new Map();
for (const p of devNpm) counts.set(p.license, (counts.get(p.license) ?? 0) + 1);
out.push(`### npm: all ${devNpm.length} development packages by license`);
out.push('');
out.push('| License | Packages |');
out.push('|---|---|');
for (const [license, n] of [...counts].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))) {
  out.push(`| ${license} | ${n} |`);
}
out.push('');

const review = devNpm.filter((p) => !PERMISSIVE.test(p.license));
if (review.length) {
  out.push('Licenses outside the usual permissive set (development tools only, not part of any build output):');
  out.push('');
  for (const p of review) out.push(`- ${p.name} ${p.version}: ${p.license}`);
  out.push('');
}

out.push('### NuGet: build-only packages');
out.push('');
out.push('| Package | Version | License |');
out.push('|---|---|---|');
for (const p of nugetPackages.filter((n) => !SHIPPED_NUGET.has(n.name))) {
  out.push(`| ${p.name} | ${p.version} | ${nugetLicense(p).expression} |`);
}
out.push('');

const text = out.join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? normalize(readFileSync(OUT, 'utf8')) : '';
  if (current !== normalize(text)) {
    console.error('THIRD_PARTY_NOTICES.md is out of date. Run: node tools/third-party-notices.mjs');
    process.exit(1);
  }
  console.log('THIRD_PARTY_NOTICES.md is up to date.');
} else {
  writeFileSync(OUT, text);
  console.log(`Wrote ${OUT}: ${shippedNpm.length + SHIPPED_NUGET.size} distributed components.`);
}
